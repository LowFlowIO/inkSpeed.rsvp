#!/usr/bin/env python3
"""Rasterize the built-in 1-bit faces.

Default source is Inter Medium. Glyphs are drawn at 4x and reduced so stems
stay one solid pixel on the 200x200 panel, instead of a fuzzy hard threshold
of the outline. The result is a bitmap Modified Version and must not be
presented as the Inter font. Inter is SIL Open Font License 1.1.
"""
from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CODEPOINTS = list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026,
]
FACES = (("small", 15), ("medium", 22), ("large", 32))
SCALE = 4


def pack_bitmap(pixels: list[int], width: int, height: int) -> bytes:
    out = bytearray((width * height + 7) // 8)
    for i, bit in enumerate(pixels):
        if bit:
            out[i // 8] |= 0x80 >> (i % 8)
    return bytes(out)


def clamp8(v: int) -> int:
    return max(-128, min(127, int(v)))


def raster_glyph(font: ImageFont.FreeTypeFont, cp: int):
    ch = chr(cp)
    if ch.isspace() and cp != 0xA0:
        advance = max(1, int(round(font.getlength(ch) or font.getlength(" "))))
        return 0, 0, 0, 0, advance, b""
    bbox = font.getbbox(ch, anchor="ls")
    if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
        advance = max(1, int(round(font.getlength(ch) or font.getlength(" "))))
        return 0, 0, 0, 0, advance, b""
    x0, y0, x1, y1 = bbox
    big = Image.new("L", ((x1 - x0) * SCALE + 2, (y1 - y0) * SCALE + 2), 255)
    draw = ImageDraw.Draw(big)
    draw.text(
        (1 - x0 * SCALE, 1 - y0 * SCALE),
        ch,
        font=font.font_variant(size=font.size * SCALE),
        fill=0,
        anchor="ls",
    )
    width, height = x1 - x0, y1 - y0
    src = big.load()
    pixels = []
    for yy in range(height):
        for xx in range(width):
            acc = n = 0
            for dy in range(SCALE):
                for dx in range(SCALE):
                    sx, sy = 1 + xx * SCALE + dx, 1 + yy * SCALE + dy
                    if 0 <= sx < big.width and 0 <= sy < big.height:
                        acc += src[sx, sy]
                        n += 1
            pixels.append(1 if acc / max(1, n) < 150 else 0)
    if not any(pixels):
        advance = max(1, int(round(font.getlength(ch))))
        return 0, 0, 0, 0, advance, b""
    advance = max(width, int(round(font.getlength(ch))))
    return width, height, x0, y0, advance, pack_bitmap(pixels, width, height)


def generate(ttf: Path, out_c: Path) -> None:
    lines = [
        "/* Auto-generated by tools/gen_font.py. Do not edit by hand.",
        " *",
        " * 1-bit faces rasterized from Inter Medium (SIL Open Font License 1.1,",
        " * Copyright 2016 The Inter Project Authors). Supersampled 4x and reduced",
        " * so stems stay solid on the 200x200 panel. Bitmap glyphs only: do not",
        " * present this as the Inter font.",
        " */",
        '#include "font_priv.h"',
        "",
    ]
    face_names = []
    for label, px in FACES:
        font = ImageFont.truetype(str(ttf), px)
        ascent, descent = font.getmetrics()
        descent = abs(descent)
        line_height = ascent + descent + 1
        space_advance = max(1, int(round(font.getlength(" "))))
        blob = bytearray()
        glyphs = []
        for cp in CODEPOINTS:
            width, height, xoff, yoff, advance, packed = raster_glyph(font, cp)
            off = len(blob)
            blob.extend(packed)
            glyphs.append((cp, width, height, clamp8(xoff), clamp8(yoff), clamp8(advance), off))
        lines.append(f"static const uint8_t font_bits_{label}[] = {{")
        for i in range(0, len(blob), 16):
            chunk = ", ".join(f"0x{b:02x}" for b in blob[i : i + 16])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
        lines.append(f"static const font_glyph_t font_glyphs_{label}[] = {{")
        for cp, width, height, xoff, yoff, advance, off in glyphs:
            lines.append(
                f"    {{0x{cp:04X}, {width}, {height}, {xoff}, {yoff}, {advance}, {off}}},"
            )
        lines.append("};")
        lines.append("")
        lines.append(f"static const font_face_t font_face_{label} = {{")
        lines.append(f'    "{label}", {px}, {ascent}, {descent}, {line_height}, {space_advance},')
        lines.append(f"    font_glyphs_{label}, {len(glyphs)}, font_bits_{label}")
        lines.append("};")
        lines.append("")
        face_names.append(label)
        print(f"{label}: {px}px, {len(glyphs)} glyphs, {len(blob)} bytes")
    lines.append("const font_face_t *const font_faces[FONT_COUNT] = {")
    for label in face_names:
        lines.append(f"    &font_face_{label},")
    lines.append("};")
    lines.append("")
    out_c.write_text("\n".join(lines) + "\n")
    print(f"wrote {out_c}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", type=Path, default=Path("/usr/share/fonts/opentype/inter/Inter-Medium.otf"))
    ap.add_argument("--out", type=Path, default=Path("src/font_data.c"))
    args = ap.parse_args()
    generate(args.ttf, args.out)


if __name__ == "__main__":
    main()
